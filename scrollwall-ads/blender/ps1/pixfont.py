def text_size(s, scale=1, spacing=1):
    return (len(s) * (5 + spacing) - spacing) * scale, 7 * scale


def draw(img, xy, s, color, scale=1, spacing=1, shadow=None):
    """Draw text onto a PIL image at pixel position xy (top-left)."""
    px = img.load()
    x0, y0 = xy
    for pass_ in ((1, shadow), (0, color)) if shadow else ((0, color),):
        off, col = pass_
        x = x0 + off * scale
        for ch in s.upper():
            g = G.get(ch, G['?'])
            for gy, row in enumerate(g):
                for gx, bit in enumerate(row):
                    if bit == '1':
                        for sy in range(scale):
                            for sx in range(scale):
                                X, Y = x + gx * scale + sx, y0 + off * scale + gy * scale + sy
                                if 0 <= X < img.width and 0 <= Y < img.height:
                                    px[X, Y] = col
            x += (5 + spacing) * scale


def draw_centered(img, cx, y, s, color, scale=1, shadow=None):
    w, _ = text_size(s, scale)
    draw(img, (cx - w // 2, y), s, color, scale, shadow=shadow)
